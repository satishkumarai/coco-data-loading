-- 1. Standard Snowpipe for AWS S3 with Auto-Ingest and Case-Insensitive Column Matching
CREATE OR REPLACE PIPE RAW_DB.INGEST_SCHEMA.PIPE_AWS_EVENTS_AUTOINGEST
  AUTO_INGEST = TRUE
  INTEGRATION = NI_AWS_EVENTS_SQS
  COMMENT = 'Snowpipe continuous ingestion pipeline from S3 events stage'
AS
COPY INTO RAW_DB.INGEST_SCHEMA.EVENTS_RAW
FROM @RAW_DB.INGEST_SCHEMA.STAGE_AWS_S3_EVENTS
FILE_FORMAT = (FORMAT_NAME = 'RAW_DB.INGEST_SCHEMA.FF_PARQUET_VECTORIZED')
MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
ON_ERROR = ABORT_STATEMENT;

-- 2. Snowpipe for Azure Blob / ADLS Gen2 with CSV Case-Insensitive Matching
CREATE OR REPLACE PIPE RAW_DB.INGEST_SCHEMA.PIPE_AZURE_ORDERS_AUTOINGEST
  AUTO_INGEST = TRUE
  INTEGRATION = NI_AZURE_ORDERS_EVENTGRID
