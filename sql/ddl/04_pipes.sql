ON_ERROR = ABORT_STATEMENT;

-- 3. Snowpipe for Snowflake-Managed Iceberg Table using LOAD_MODE = ADD_FILES_COPY
-- (For Parquet files generated by an external compliant Apache Iceberg writer)
CREATE OR REPLACE PIPE RAW_DB.INGEST_SCHEMA.PIPE_ICEBERG_ADDFILES_AUTOINGEST
  AUTO_INGEST = TRUE
  INTEGRATION = NI_AWS_EVENTS_SQS
  COMMENT = 'Snowpipe Iceberg metadata registration pipeline via zero-copy ADD_FILES_COPY'
AS
COPY INTO RAW_DB.INGEST_SCHEMA.ICEBERG_PAGEVIEWS_MANAGED
FROM @RAW_DB.INGEST_SCHEMA.STAGE_AWS_S3_EVENTS
FILE_FORMAT = (FORMAT_NAME = 'RAW_DB.INGEST_SCHEMA.FF_PARQUET_VECTORIZED')
LOAD_MODE = ADD_FILES_COPY
MATCH_BY_COLUMN_NAME = CASE_SENSITIVE
ON_ERROR = ABORT_STATEMENT;

-- 4. Snowpipe for Snowflake-Managed Iceberg Table using LOAD_MODE = FULL_INGEST
-- (For raw Parquet, CSV, or JSON requiring full conversion to Iceberg data files)
